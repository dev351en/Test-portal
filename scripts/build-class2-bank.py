"""Publish the approved Class 2 dataset, source illustrations and redesigned PDF.

Run with the worksheet project's Python environment (PyMuPDF is required):
  python scripts/build-class2-bank.py --source-dir "../DASS/D3V3NDRA Classes"
"""
import argparse
import base64
import importlib.util
import json
from pathlib import Path
import shutil

import pymupdf


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source-dir", type=Path, required=True)
    source = parser.parse_args().source_dir.resolve()
    root = Path(__file__).resolve().parent.parent
    data = json.loads((source / "data/class2_test_paper_1.json").read_text(encoding="utf-8"))
    spec = importlib.util.spec_from_file_location("worksheet", source / "scripts/build_class2_test1_worksheet.py")
    worksheet = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(worksheet)
    assets = root / "assets/class2-test1"
    assets.mkdir(parents=True, exist_ok=True)

    def save_image(uri, filename):
        mime, encoded = uri.split(",", 1)
        content = base64.b64decode(encoded)
        if "svg" in mime:
            # PNG retains the exact source paths and also works in email clients.
            with pymupdf.open(stream=content, filetype="svg") as svg:
                content = svg[0].get_pixmap(matrix=pymupdf.Matrix(4, 4), alpha=False).tobytes("png")
        (assets / filename).write_bytes(content)
        return f"assets/class2-test1/{filename}"

    bank = []
    with pymupdf.open(source / data["source_pdf"]) as doc:
        assert worksheet.extract_questions(doc) == data["questions"], "Dataset differs from the approved source"
        for q in data["questions"]:
            n = q["num"]
            item = {"id": n, "q": q["q"], "opts": q["options"],
                    "ans": "ABCD".index(q["ans"]), "marks": q["marks"],
                    "cat": q["section"], "sol": " ".join(q["solution_steps"]), "diagram": ""}
            if str(n) in data["diagram_sources"]:
                page, xref, _ = data["diagram_sources"][str(n)]
                item["diagram"] = save_image(worksheet.image_uri(doc, page, xref), f"q{n:02}.png")
            if str(n) in data["option_image_sources"]:
                item["optionImages"] = [save_image(worksheet.image_uri(doc, q["source_page"], xref),
                    f"q{n:02}-{letter}.png") for letter, xref in zip("abcd", data["option_image_sources"][str(n)])]
            if str(n) in data["option_drawing_sources"]:
                page, drawings = data["option_drawing_sources"][str(n)]
                item["optionImages"] = [save_image(worksheet.drawing_uri(doc, page, drawing),
                    f"q{n:02}-{letter}.png") for letter, drawing in zip("abcd", drawings)]
            bank.append(item)
    assert len(bank) == 35 and sum(q["marks"] for q in bank) == 45
    assert sum(bool(q["diagram"]) for q in bank) == 15
    assert sum(len(q.get("optionImages", [])) for q in bank) == 12
    (root / "class2_questions.js").write_text(
        "// Approved Class 2 Test Paper 1: exact source question, option and key order.\n"
        "// Generated by scripts/build-class2-bank.py. Image-only options retain empty text.\n"
        "window.CLASS2_QUESTIONS = " + json.dumps(bank, ensure_ascii=False, indent=2) + ";\n", encoding="utf-8")
    shutil.copyfile(source / "output/Worksheet Class 2 Test Paper 1.pdf", root / "assets/worksheet-class2-test-paper-1.pdf")
    print("Published 35 questions, 45 marks, 27 illustrations and the approved worksheet PDF.")


if __name__ == "__main__":
    main()
